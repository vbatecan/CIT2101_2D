namespace CaseClosed.Enums
{
    /// <summary>
    /// Represents the facial and emotional expressions displayed by suspects and witnesses during investigation and interrogation.
    /// </summary>
    public enum CharacterExpression
    {
        /// <summary>Default composed facial expression.</summary>
        Neutral,

        /// <summary>Inquisitive or questioning look.</summary>
        Curious,

        /// <summary>Uneasy, trembling, or anxious look.</summary>
        Nervous,

        /// <summary>Aggressive or irritated expression.</summary>
        Angry,

        /// <summary>Downcast or remorseful expression.</summary>
        Sad,

        /// <summary>Caught off guard expression.</summary>
        Surprised,

        /// <summary>Guarded, cross-armed, or suspicious look.</summary>
        Defensive,

        /// <summary>Visibly rattled by an exposed contradiction.</summary>
        Shocked,

        /// <summary>Pondering or recalling information.</summary>
        Thinking,

        /// <summary>Overconfident or dismissive grin.</summary>
        Smug
    }
}
